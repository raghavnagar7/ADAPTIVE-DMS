@st.cache_data(ttl=2)
def load_events(
    file_path,
    file_modified_time,
):

    try:

        if not os.path.exists(
            file_path
        ):

            return pd.DataFrame(
                columns=[
                    "timestamp",
                    "event_type",
                    "severity",
                    "message",
                ]
            )

        file_size = os.path.getsize(
            file_path
        )

        if file_size <= 0:

            return pd.DataFrame(
                columns=[
                    "timestamp",
                    "event_type",
                    "severity",
                    "message",
                ]
            )

        # -----------------------------------------------------
        # Read only a limited amount of event data
        # -----------------------------------------------------

        max_bytes = 256 * 1024

        bytes_to_read = min(
            file_size,
            max_bytes,
        )

        with open(
            file_path,
            "rb",
        ) as file:

            file.seek(
                -bytes_to_read,
                os.SEEK_END,
            )

            raw_data = file.read()

        text = raw_data.decode(
            "utf-8",
            errors="ignore",
        )

        lines = text.splitlines()

        if not lines:

            return pd.DataFrame()

        # -----------------------------------------------------
        # Find header
        # -----------------------------------------------------

        header = (
            "timestamp,event_type,severity,message"
        )

        header_index = -1

        for index, line in enumerate(
            lines
        ):

            if line.strip() == header:

                header_index = index

                break

        if header_index >= 0:

            data_lines = lines[
                header_index + 1:
            ]

        else:

            data_lines = lines

        if not data_lines:

            return pd.DataFrame(
                columns=[
                    "timestamp",
                    "event_type",
                    "severity",
                    "message",
                ]
            )

        # -----------------------------------------------------
        # Limit events
        # -----------------------------------------------------

        if len(data_lines) > MAX_EVENTS:

            data_lines = data_lines[
                -MAX_EVENTS:
            ]

        reader = csv.reader(
            data_lines
        )

        rows = []

        for row in reader:

            if len(row) < 4:

                continue

            rows.append(
                [
                    row[0],
                    row[1],
                    row[2],
                    ",".join(
                        row[3:]
                    ),
                ]
            )

        if not rows:

            return pd.DataFrame()

        df = pd.DataFrame(
            rows,
            columns=[
                "timestamp",
                "event_type",
                "severity",
                "message",
            ],
        )

        # -----------------------------------------------------
        # Convert timestamp
        # -----------------------------------------------------

        df["timestamp"] = pd.to_datetime(
            df["timestamp"],
            errors="coerce",
        )

        df = df.dropna(
            subset=[
                "timestamp"
            ]
        )

        # -----------------------------------------------------
        # Sort newest first
        # -----------------------------------------------------

        df = df.sort_values(
            "timestamp",
            ascending=False,
        )

        return df.reset_index(
            drop=True
        )

    except (
        OSError,
        PermissionError,
        MemoryError,
        UnicodeError,
        csv.Error,
    ):

        return pd.DataFrame()


