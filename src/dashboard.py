@st.cache_data(ttl=2)
def load_recent_data(
    file_path,
    file_modified_time,
):

    try:

        if not os.path.exists(
            file_path
        ):

            return pd.DataFrame()

        file_size = os.path.getsize(
            file_path
        )

        if file_size <= 0:

            return pd.DataFrame()

        # -----------------------------------------------------
        # Read header
        # -----------------------------------------------------

        with open(
            file_path,
            "r",
            encoding="utf-8",
            errors="ignore",
            newline="",
        ) as file:

            header_line = file.readline()

        if not header_line:

            return pd.DataFrame()

        header_line = header_line.strip()

        if not header_line:

            return pd.DataFrame()

        # -----------------------------------------------------
        # Read last 512 KB only
        # -----------------------------------------------------

        max_bytes = 512 * 1024

        bytes_to_read = min(
            file_size,
            max_bytes,
        )

        with open(
            file_path,
            "rb",
        ) as file:

            file.seek(
                -bytes_to_read,
                os.SEEK_END,
            )

            raw_data = file.read()

        text = raw_data.decode(
            "utf-8",
            errors="ignore",
        )

        lines = text.splitlines()

        if len(lines) < 2:

            return pd.DataFrame()

        data_lines = lines[1:]

        if not data_lines:

            return pd.DataFrame()

        # -----------------------------------------------------
        # Keep latest rows
        # -----------------------------------------------------

        if len(data_lines) > MAX_ROWS:

            data_lines = data_lines[
                -MAX_ROWS:
            ]

        # -----------------------------------------------------
        # Header
        # -----------------------------------------------------

        header_reader = csv.reader(
            [header_line]
        )

        headers = next(
            header_reader
        )

        if not headers:

            return pd.DataFrame()

        header_length = len(
            headers
        )

        # -----------------------------------------------------
        # Parse rows
        # -----------------------------------------------------

        reader = csv.reader(
            data_lines
        )

        valid_rows = []

        for row in reader:

            if not row:

                continue

            if len(row) < 5:

                continue

            if len(row) == header_length:

                valid_rows.append(
                    row
                )

            elif len(row) > header_length:

                valid_rows.append(
                    row[
                        :header_length
                    ]
                )

            else:

                padded_row = (
                    row
                    + [""] * (
                        header_length
                        - len(row)
                    )
                )

                valid_rows.append(
                    padded_row
                )

        if not valid_rows:

            return pd.DataFrame()

        df = pd.DataFrame(
            valid_rows,
            columns=headers,
        )

        if df.empty:

            return df

        # -----------------------------------------------------
        # Timestamp
        # -----------------------------------------------------

        if "timestamp" not in df.columns:

            return pd.DataFrame()

        df["timestamp"] = pd.to_datetime(
            df["timestamp"],
            errors="coerce",
        )

        df = df.dropna(
            subset=[
                "timestamp"
            ]
        )

        if df.empty:

            return df

        # -----------------------------------------------------
        # Numeric columns
        # -----------------------------------------------------

        numeric_columns = [

            "ear",
            "mar",
            "perclos",
            "blink_count",
            "blink_duration",
            "microsleep_duration",
            "pitch",
            "yaw",
            "roll",
            "gaze_away_duration",
            "reliability",
            "fatigue_risk",
            "eye_closure_duration",
        ]

        for column in numeric_columns:

            if column in df.columns:

                df[column] = pd.to_numeric(
                    df[column],
                    errors="coerce",
                )

        # -----------------------------------------------------
        # Boolean columns
        # -----------------------------------------------------

        boolean_columns = [

            "eyes_closed",
            "microsleep",
            "alert_triggered",
        ]

        for column in boolean_columns:

            if column in df.columns:

                df[column] = (
                    df[column]
                    .astype(str)
                    .str.strip()
                    .str.lower()
                    .map(
                        {
                            "true": 1,
                            "false": 0,
                            "1": 1,
                            "0": 0,
                        }
                    )
                    .fillna(0)
                )

        # -----------------------------------------------------
        # Elapsed seconds
        # -----------------------------------------------------

        df["elapsed_seconds"] = (
            df["timestamp"]
            - df["timestamp"].iloc[0]
        ).dt.total_seconds()

        return df

    except (
        OSError,
        PermissionError,
        MemoryError,
        UnicodeError,
        csv.Error,
    ):

        return pd.DataFrame()


