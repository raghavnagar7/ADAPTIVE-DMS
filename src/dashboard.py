def find_latest_session():

    files = glob.glob(
        os.path.join(
            "logs",
            "session_*.csv",
        )
    )

    if not files:

        return None

    return max(
        files,
        key=os.path.getmtime,
    )


def safe_float(
    value,
    default=0.0,
):

    try:

        if pd.isna(value):

            return default

        return float(value)

    except Exception:

        return default


def safe_text(
    value,
    default="UNKNOWN",
):

    try:

        if pd.isna(value):

            return default

        return str(value)

    except Exception:

        return default


def get_file_age(
    file_path
):

    try:

        modified = os.path.getmtime(
            file_path
        )

        return (
            time.time()
            - modified
        )

    except Exception:

        return float("inf")


def is_live_frame_active():

    if not os.path.exists(
        LIVE_FRAME_PATH
    ):

        return False

    age = get_file_age(
        LIVE_FRAME_PATH
    )

    return age <= LIVE_FRAME_TIMEOUT


